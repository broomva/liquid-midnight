// Build tokens/tokens.css and the DESIGN.md token tables from tokens/tokens.json (the single source of truth).
// `bun scripts/build-tokens.mjs --check` fails if either generated output is stale.
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("..", import.meta.url).pathname;
const tokens = JSON.parse(readFileSync(`${ROOT}tokens/tokens.json`, "utf8"));
const check = process.argv.includes("--check");
export { css as buildCss };

// OKLCH -> sRGB hex (Björn Ottosson's OKLab matrices), clipped to gamut; alpha becomes the 4th byte.
export function oklchToHex(css) {
  const m = css.match(/oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+))?\s*\)/);
  if (!m) throw new Error(`not an oklch() colour: ${css}`);
  const [L, C, H] = [+m[1], +m[2], (+m[3] * Math.PI) / 180];
  const alpha = m[4] === undefined ? 1 : +m[4];
  const a = C * Math.cos(H);
  const b = C * Math.sin(H);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const mm = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * mm + 1.707614701 * s,
  ];
  const enc = (x) => {
    const v = x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
    return Math.round(Math.min(1, Math.max(0, v)) * 255);
  };
  const bytes = lin.map(enc);
  if (alpha < 1) bytes.push(Math.round(alpha * 255));
  return `#${bytes.map((v) => v.toString(16).padStart(2, "0")).join("")}`;
}

const kebab = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const v = (t) => (typeof t === "string" ? t : t.value);

function block(selector, entries, indent = "  ") {
  const hex = entries.map(([k, t]) => `${indent}--lm-${kebab(k)}: ${oklchToHex(v(t))};`).join("\n");
  const ok = entries.map(([k, t]) => `${indent}  --lm-${kebab(k)}: ${v(t)};`).join("\n");
  return `${selector} {\n${hex}\n}\n@supports (color: oklch(0 0 0)) {\n  ${selector} {\n${ok}\n  }\n}\n`;
}

function css() {
  const { color, font, motion, radius, blur } = tokens;
  const out = [
    "/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit; edit the JSON and run `bun run tokens`. */",
    "/* Hex first (fallback), OKLCH inside @supports (canonical). Modes: night (default), day/paper via [data-lm-mode=day]. */",
    "",
    block(":root, [data-lm-mode=night]", [...Object.entries(color.night), ...Object.entries(color.metal.night).map(([k, t]) => [`metal-${k}`, t])]),
    // tones override the night grounds only; they come BEFORE day so a day page keeps its paper grounds (deck :33-37)
    // and never apply inside a day subtree, wherever the two attributes sit (same element, ancestor or descendant)
    ...Object.entries(color.tone).map(([name, set]) => block(`[data-lm-tone=${name}]:not([data-lm-mode=day], [data-lm-mode=day] *)`, Object.entries(set))),
    block("[data-lm-mode=day]", [...Object.entries(color.day), ...Object.entries(color.metal.day).map(([k, t]) => [`metal-${k}`, t])]),
    ":root {",
    ...Object.entries(font).map(([k, f]) => `  --lm-font-${k}: ${f.family};`),
    ...Object.entries(radius).map(([k, r]) => `  --lm-radius-${kebab(k)}: ${r}px;`),
    ...Object.entries(blur).map(([k, b]) => `  --lm-blur-${k}: ${b}px;`),
    `  --lm-ease-out: ${motion.ease.out};`,
    `  --lm-ease-in-out: ${motion.ease.inOut};`,
    `  --lm-ua-speed: ${motion.ua.degPerSecond};`,
    "  --lm-shadow: 0 30px 80px -28px oklch(0.05 0.02 250 / 0.82), 0 8px 24px -12px oklch(0.05 0.02 250 / 0.6);",
    "}",
    "[data-lm-mode=day] {",
    "  --lm-shadow: 0 28px 70px -34px oklch(0.3 0.04 255 / 0.3), 0 8px 22px -14px oklch(0.3 0.04 255 / 0.2);",
    "}",
    "",
  ];
  return out.join("\n");
}

function tables() {
  const { color } = tokens;
  const row = (k, n, d) => `| \`--lm-${kebab(k)}\` | \`${v(n)}\` | \`${oklchToHex(v(n))}\` | \`${v(d)}\` | \`${oklchToHex(v(d))}\` | ${n.role} |`;
  const head = "| Token | Night (OKLCH) | Night hex | Day / paper (OKLCH) | Day hex | Role |\n|---|---|---|---|---|---|";
  const main = Object.keys(color.night).map((k) => row(k, color.night[k], color.day[k]));
  const metal = Object.keys(color.metal.night).map((k) => row(`metal-${k}`, color.metal.night[k], color.metal.day[k]));
  return [
    "<!-- tokens:start (generated by scripts/build-tokens.mjs; do not edit by hand) -->",
    head,
    ...main,
    "",
    "Liquid-metal palette:",
    "",
    head,
    ...metal,
    "<!-- tokens:end -->",
  ].join("\n");
}

if (import.meta.main) {
  const cssOut = css();
  const designPath = `${ROOT}DESIGN.md`;
  const design = readFileSync(designPath, "utf8");
  const re = /<!-- tokens:start[\s\S]*?<!-- tokens:end -->/;
  if (!re.test(design)) throw new Error("DESIGN.md is missing the <!-- tokens:start --> … <!-- tokens:end --> markers");
  const designOut = design.replace(re, tables());

  if (check) {
    const stale = [];
    if (readFileSync(`${ROOT}tokens/tokens.css`, "utf8") !== cssOut) stale.push("tokens/tokens.css");
    if (design !== designOut) stale.push("DESIGN.md token tables");
    if (stale.length) {
      console.error(`stale: ${stale.join(", ")}. Run \`bun run tokens\`.`);
      process.exit(1);
    }
    console.log("tokens: up to date");
  } else {
    writeFileSync(`${ROOT}tokens/tokens.css`, cssOut);
    writeFileSync(designPath, designOut);
    console.log("tokens: wrote tokens/tokens.css and DESIGN.md tables");
  }
}
